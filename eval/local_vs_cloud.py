#!/usr/bin/env python3
"""Benchmarks the local, on-device LLM backend (Ollama, default) against the optional
cloud backend (Gemini) on three axes: routing-classification accuracy, per-call
latency, and end-to-end retrieval quality (NDCG@10/Precision@5) when the LLM is used
for deep-route query enrichment.

This is Objective 3 evidence (on-device optimization under compute constraints), not
a compliance checkbox: it's the direct answer to "what do you give up by requiring
this to run fully offline on a laptop instead of calling a cloud API."

    python eval/local_vs_cloud.py

Requires:
  - `ollama serve` running locally with OLLAMA_MODEL pulled (local backend)
  - GEMINI_API_KEY set (cloud backend) — if absent, the cloud arm is skipped and
    reported as such rather than faked.

Writes eval/results/local_vs_cloud_summary.json and eval/results/local_vs_cloud.png.
"""

from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path
from statistics import mean

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from sqlmodel import select  # noqa: E402

from app.agent.graph import run_query  # noqa: E402
from app.agent.query_understanding import extract_entities  # noqa: E402
from app.agent.router import _llm_classify  # noqa: E402
from app.db import get_session  # noqa: E402
from app.llm_client import get_client  # noqa: E402
from app.models import UserRecord  # noqa: E402
from eval.metrics import mrr, ndcg_at_k, precision_at_k, recall_at_k  # noqa: E402
from eval.run_benchmark import EVAL_SET_PATH, RESULTS_DIR, load_eval_set  # noqa: E402

ROUTER_LABELS_PATH = REPO_ROOT / "eval" / "router_labels.json"
K_NDCG = 10
K_PRECISION = 5


def _set_backend(backend: str) -> None:
    os.environ["LLM_BACKEND"] = backend


def backend_available(backend: str) -> bool:
    _set_backend(backend)
    return get_client().is_available


def bench_routing_accuracy(backend: str, labels: list[dict]) -> dict:
    """Agreement with the ground-truth tier in router_labels.json. Note: those labels
    were themselves generated by the cloud backend (eval/build_router_labels.py), so
    the cloud number here is a near-100% sanity check by construction, not an
    independent accuracy measure — the local number is the one that actually says
    something, since it's being checked against a different model's judgment."""
    _set_backend(backend)
    correct = 0
    latencies = []
    for item in labels:
        intent = extract_entities(item["query"])
        t0 = time.perf_counter()
        decision = _llm_classify(intent)
        latencies.append(time.perf_counter() - t0)
        if decision is not None and decision.tier == item["llm_tier"]:
            correct += 1
    return {
        "n_queries": len(labels),
        "agreement_with_ground_truth": correct / len(labels) if labels else None,
        "mean_latency_ms": mean(latencies) * 1000 if latencies else None,
    }


def bench_retrieval_quality(backend: str, hard_queries: list[dict], user_ids: list[int]) -> dict:
    """Runs the hard-tier (deep-route, LLM-enrichment-eligible) queries through the
    real pipeline with the given backend active, reusing the exact same run_query()
    the production system calls — not a simulated proxy."""
    _set_backend(backend)
    rows = []
    latencies = []
    for q in hard_queries:
        relevant = set(q["ground_truth_file_ids"])
        for user_id in user_ids:
            t0 = time.perf_counter()
            out = run_query(q["query"], user_id)
            latencies.append(time.perf_counter() - t0)
            ranked_ids = [r["file_id"] for r in out["results"]]
            rows.append(
                {
                    "precision_at_5": precision_at_k(ranked_ids, relevant, K_PRECISION),
                    "recall_at_5": recall_at_k(ranked_ids, relevant, K_PRECISION),
                    "ndcg_at_10": ndcg_at_k(ranked_ids, relevant, K_NDCG),
                    "mrr": mrr(ranked_ids, relevant),
                    "llm_call_count": out["routing_trace"]["llm_call_count"],
                }
            )
    return {
        "n_runs": len(rows),
        "precision_at_5": mean(r["precision_at_5"] for r in rows),
        "recall_at_5": mean(r["recall_at_5"] for r in rows),
        "ndcg_at_10": mean(r["ndcg_at_10"] for r in rows),
        "mrr": mean(r["mrr"] for r in rows),
        "mean_llm_calls_per_query": mean(r["llm_call_count"] for r in rows),
        "mean_latency_ms": mean(latencies) * 1000 if latencies else None,
    }


def plot_comparison(result: dict, out_path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    backends = [b for b in ("local", "cloud") if result["retrieval_quality"].get(b)]
    if not backends:
        return

    fig, axes = plt.subplots(1, 2, figsize=(11, 5))

    metrics = ["precision_at_5", "recall_at_5", "ndcg_at_10", "mrr"]
    x = range(len(metrics))
    width = 0.35
    for i, b in enumerate(backends):
        vals = [result["retrieval_quality"][b][m] for m in metrics]
        axes[0].bar([xi + (i - 0.5) * width for xi in x], vals, width, label=b)
    axes[0].set_xticks(list(x))
    axes[0].set_xticklabels(metrics, rotation=20, ha="right")
    axes[0].set_title("Retrieval quality (hard tier)")
    axes[0].legend()
    axes[0].set_ylim(0, 1.0)

    lat_labels = backends
    lat_vals = [result["retrieval_quality"][b]["mean_latency_ms"] for b in backends]
    axes[1].bar(lat_labels, lat_vals, color=["#4c72b0", "#dd8452"][: len(backends)])
    axes[1].set_title("Mean end-to-end latency per query (ms)")
    axes[1].set_ylabel("ms")

    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def main() -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    result: dict = {"routing_accuracy": {}, "retrieval_quality": {}}

    labels = json.loads(ROUTER_LABELS_PATH.read_text()) if ROUTER_LABELS_PATH.exists() else []
    eval_set = load_eval_set()
    hard_queries = [q for q in eval_set if q["difficulty"] == "hard"]
    with get_session() as session:
        user_ids = [u.id for u in session.exec(select(UserRecord)).all()]

    for backend in ("local", "cloud"):
        available = backend_available(backend)
        print(f"[local_vs_cloud] backend={backend} available={available}")
        if not available:
            result["routing_accuracy"][backend] = None
            result["retrieval_quality"][backend] = None
            continue

        if labels:
            print(f"[local_vs_cloud]   routing accuracy on {len(labels)} labeled queries...")
            result["routing_accuracy"][backend] = bench_routing_accuracy(backend, labels)
            print(f"    {result['routing_accuracy'][backend]}")
        else:
            result["routing_accuracy"][backend] = None
            print("[local_vs_cloud]   router_labels.json not found, skipping routing accuracy")

        print(f"[local_vs_cloud]   retrieval quality on {len(hard_queries)} hard queries x {len(user_ids)} users...")
        result["retrieval_quality"][backend] = bench_retrieval_quality(backend, hard_queries, user_ids)
        print(f"    {result['retrieval_quality'][backend]}")

    result["_note"] = (
        "routing_accuracy is measured against eval/router_labels.json, which was itself "
        "generated by the cloud backend — the cloud number there is a near-100% sanity "
        "check by construction, not an independent accuracy measure. The local number "
        "is the meaningful one: how well an on-device 1.5B model approximates a larger "
        "cloud model's judgment. retrieval_quality has no such issue — ground truth "
        "there is the hand-labeled eval set, independent of either backend."
    )

    summary_path = RESULTS_DIR / "local_vs_cloud_summary.json"
    summary_path.write_text(json.dumps(result, indent=2))
    plot_comparison(result, RESULTS_DIR / "local_vs_cloud.png")

    print(f"\nwrote {summary_path}")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
